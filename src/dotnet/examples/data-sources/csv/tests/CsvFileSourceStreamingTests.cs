    [TestMethod]
    public void Compile_WhenEncodingModifiersConflict_ShouldReportContractError()
    {
        var path = WriteTempCsv("Name,Other\nAda,Value\n");
        var query =
            "table CsvShape { Name: string encoding 'utf-8', Other: string encoding 'utf-16le' };" +
            "couple #csv.file with table CsvShape as Rows;" +
            $"select Name, Other from Rows({SqlString(path)}, true)";

        var result = CompileWithDiagnostics(query);

        Assert.IsFalse(result.Succeeded);
        var error = result.Errors.Single(item => item.Code == DiagnosticCode.MQ3071_SourceContractError);
        StringAssert.Contains(error.Message, "CsvInconsistentEncoding");
        StringAssert.Contains(error.Message, "column=Other");
        StringAssert.Contains(error.Message, "modifier=encoding");
    }

    [TestMethod]
    public void Execution_WhenRowsExceedChunkSize_ShouldReportRowsReadProgress()
    {
        var rows = string.Join("\n", Enumerable.Range(0, 35).Select(static index => $"Name{index}"));
        var path = WriteTempCsv($"Name\n{rows}\n");
        var query =
            "table CsvShape { Name: string };" +
            "couple #csv.file with table CsvShape as Rows;" +
            $"select Name from Rows({SqlString(path)}, true)";
        var progress = new List<DataSourceEventArgs>();

        var compiled = Compile(query);
        compiled.DataSourceProgress += (_, args) => progress.Add(args);
        var table = compiled.Run();

        Assert.AreEqual(35, table.Count);
        CollectionAssert.AreEqual(
            new[]
            {
                DataSourcePhase.Begin,
                DataSourcePhase.RowsRead,
                DataSourcePhase.RowsRead,
                DataSourcePhase.End
            },
            progress.Select(static item => item.Phase).ToArray());
        CollectionAssert.AreEqual(
            new long?[] { 32, 35 },
            progress
                .Where(static item => item.Phase == DataSourcePhase.RowsRead)
                .Select(static item => item.RowsProcessed)
                .ToArray());
        Assert.AreEqual(35, progress.Last().RowsProcessed);
    }

    [TestMethod]
    public void Source_WhenCancellationIsRequested_ShouldStopStreaming()
    {
        var path = WriteTempCsv("Name\nAda\n");
        using var cancellation = new CancellationTokenSource();
        cancellation.Cancel();
        var context = new SourceExecutionContext(
            "cancel-query",
            SourceExecutionPlan.Empty(SourceIdentity.Empty),
            cancellation.Token,
            [Column("Name", 0, typeof(string))],
            new Dictionary<string, string>(),
            NullLogger.Instance);
        var source = new CsvFileSource(path, true, context);

        Assert.Throws<OperationCanceledException>(() => source.Chunks.SelectMany(static chunk => chunk).ToArray());
    }

    [TestMethod]
    public void Source_WhenCsvHasMalformedQuotes_ShouldThrowFormatException()
    {
        var path = WriteTempCsv("Name\n\"Ada\n");
        var context = new SourceExecutionContext(
            "malformed-query",
            SourceExecutionPlan.Empty(SourceIdentity.Empty),
            CancellationToken.None,
            [Column("Name", 0, typeof(string))],
            new Dictionary<string, string>(),
            NullLogger.Instance);
        var source = new CsvFileSource(path, true, context);

        Assert.Throws<FormatException>(() => source.Chunks.SelectMany(static chunk => chunk).ToArray());
    }
}
