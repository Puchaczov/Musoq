using System.Text;
using Microsoft.Extensions.Logging.Abstractions;
using Musoq.Parser.Diagnostics;
using Musoq.Schema;
using Musoq.Schema.Optimization;

namespace Musoq.Examples.DataSources.Csv.Tests;

[TestClass]
public sealed class CsvFileSourceStreamingTests : CsvExampleTestBase
{
    [TestMethod]
    public void Execution_WhenCsvHasHeader_ShouldMapByHeaderAndConvertTypes()
    {
        var path = WriteTempCsv(
            "Name,Amount,When\n" +
            "Ada,\"12,50\",31.12.2023\n" +
            "Bob,\"2,40\",01.01.2024\n");
        var query =
            "table CsvShape { Name: string, Amount: decimal culture 'pl-PL', EventDate: datetime source name 'When' format 'dd.MM.yyyy' };" +
            "couple #csv.file with table CsvShape as Rows;" +
            $"select Name, Amount, EventDate from Rows({SqlString(path)}, true) order by Name";

        var table = Run(query);

        Assert.AreEqual(2, table.Count);
        Assert.AreEqual("Ada", table[0][0]);
        Assert.AreEqual(12.50m, table[0][1]);
        Assert.AreEqual(new DateTime(2023, 12, 31), table[0][2]);
        Assert.AreEqual("Bob", table[1][0]);
        Assert.AreEqual(2.40m, table[1][1]);
        Assert.AreEqual(new DateTime(2024, 1, 1), table[1][2]);
    }

    [TestMethod]
    public void Execution_WhenCsvHasNoHeader_ShouldMapByOrdinalAndSourceIndex()
    {
        var path = WriteTempCsv("1,Ada,ignored\n2,Bob,ignored\n");
        var query =
            "table CsvShape { Id: int, Name: string source index '1' };" +
