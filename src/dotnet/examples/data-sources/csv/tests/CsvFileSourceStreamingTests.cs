    [TestMethod]
    public void Execution_WhenCsvHasNullableOrMissingFields_ShouldReturnNull()
    {
        var path = WriteTempCsv("Name,Amount,Count\nAda,,\nBob,12.5\n");
        var query =
            "table CsvShape { Name: string, Amount: decimal?, Count: int? };" +
            "couple #csv.file with table CsvShape as Rows;" +
            $"select Name, Amount, Count from Rows({SqlString(path)}, true) order by Name";

        var table = Run(query);

        Assert.AreEqual(2, table.Count);
        Assert.AreEqual("Ada", table[0][0]);
        Assert.IsNull(table[0][1]);
        Assert.IsNull(table[0][2]);
        Assert.AreEqual("Bob", table[1][0]);
        Assert.AreEqual(12.5m, table[1][1]);
        Assert.IsNull(table[1][2]);
    }

