using System.Collections.Generic;
using System.Text;
using Musoq.Parser.Nodes.InterpretationSchema;

namespace Musoq.Evaluator.Visitors;

/// <summary>
///     Generates C# interpreter classes from binary and text schema AST nodes.
///     The generated classes inherit from BytesInterpreterBase or TextInterpreterBase
///     and implement the actual parsing logic.
/// </summary>
public partial class InterpreterCodeGenerator
{
    private readonly Dictionary<string, string> _generatedCode = new(StringComparer.OrdinalIgnoreCase);

    private readonly SchemaRegistry _registry;
    private readonly int _maxRepeatIterations;
    private string _currentSchemaName = "<unknown>";
    private string[] _currentTypeParameters = Array.Empty<string>();
    private int _discardCounter;
    private IReadOnlyList<SchemaFieldNode> _expressionFields = Array.Empty<SchemaFieldNode>();
    private string _intrinsicTypeName = string.Empty;
    private int _intrinsicCallCount;
    private StringConcatenationCodeEmitter _stringConcatenation = new("__MusoqSchemaConcat");
    private string _activeSchemaFieldName = string.Empty;

    /// <summary>
    ///     Creates a new interpreter code generator.
    /// </summary>
    /// <param name="registry">The schema registry containing schema definitions.</param>
    public InterpreterCodeGenerator(SchemaRegistry registry)
        : this(registry, InterpretationExecutionLimits.Default) { }

    /// <summary>Creates a generator that compiles the selected limits into every interpreter.</summary>
    public InterpreterCodeGenerator(SchemaRegistry registry, InterpretationExecutionLimits limits)
    {
        ArgumentNullException.ThrowIfNull(limits);
        _registry = registry ?? throw new ArgumentNullException(nameof(registry));
        _maxRepeatIterations = limits.MaxRepeatIterations;
    }

    /// <summary>
    ///     Gets the generated source code for all schemas.
    ///     Key is schema name, value is the C# source code.
    /// </summary>
    public IReadOnlyDictionary<string, string> GeneratedCode => _generatedCode;

    /// <summary>
    ///     Generates C# code for all schemas in the registry.
    /// </summary>
    /// <param name="namespaceName">The namespace for the generated classes.</param>
    /// <returns>Complete C# source code containing all generated interpreter classes.</returns>
    public string GenerateAll(string namespaceName = "Musoq.Generated.Interpreters")
    {
        var intrinsicName = "__MusoqSchemaIntrinsics";
        while (_registry.TryGetSchema(intrinsicName, out _))
            intrinsicName += "_";
        _intrinsicTypeName = $"global::{namespaceName}.{intrinsicName}";
        _intrinsicCallCount = 0;
        _stringConcatenation = new StringConcatenationCodeEmitter(
            SchemaConcatenationNames.Create(_registry, intrinsicName)
        );
        var builder = new StringBuilder();

        builder.AppendLine("// <auto-generated>");
        builder.AppendLine("// This code was generated by Musoq Interpretation Schema code generator.");
        builder.AppendLine("// Do not modify this file directly.");
        builder.AppendLine("// </auto-generated>");
        builder.AppendLine();
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine("using System;");
        builder.AppendLine("using System.Buffers.Binary;");
        builder.AppendLine("using System.Collections.Generic;");
        builder.AppendLine("using System.Dynamic;");
        builder.AppendLine("using Musoq.Schema.Interpreters;");
        builder.AppendLine();
        builder.AppendLine(System.Globalization.CultureInfo.InvariantCulture, $"namespace {namespaceName}");
        builder.AppendLine("{");

        foreach (var registration in _registry.Schemas)
            if (registration.Node is BinarySchemaNode binarySchema)
            {
                var classCode = GenerateBinaryInterpreterClass(binarySchema);
                _generatedCode[registration.Name] = classCode;
                builder.AppendLine(Indent(classCode, 1));
                builder.AppendLine();

                foreach (var (_, type) in BinaryCompositionTypes.EnumerateFields(binarySchema.Fields))
                {
                    var nestedCode = type switch
                    {
                        InlineSchemaTypeNode inline => GenerateInlineSchemaNestedClass(
                            _registry.BinaryCompositions.Name(inline),
                            inline
                        ),
                        BinarySwitchTypeNode choice => GenerateSwitchNestedClass(
                            _registry.BinaryCompositions.Name(choice),
                            choice
                        ),
                        _ => null,
                    };
                    if (nestedCode != null)
                        builder.AppendLine(Indent(nestedCode, 1)).AppendLine();
                }
            }
            else if (registration.Node is TextSchemaNode textSchema)
            {
                var classCode = GenerateTextInterpreterClass(textSchema);
                _generatedCode[registration.Name] = classCode;
                builder.AppendLine(Indent(classCode, 1));
                builder.AppendLine();
            }

        if (_intrinsicCallCount > 0)
            builder.AppendLine(Indent(SchemaIntrinsicCodeEmitter.Emit(intrinsicName), 1));
        var concatenationCallbacks = _stringConcatenation.EmitCallbackClass();
        if (concatenationCallbacks.Length != 0)
            builder.AppendLine(Indent(concatenationCallbacks, 1));
        builder.AppendLine("}");

        return builder.ToString();
    }

    private string GetLocalVarName(string fieldName)
    {
        if (fieldName == "_")
            return $"_discard{_discardCounter++}";
        return string.Create(
            System.Globalization.CultureInfo.InvariantCulture,
            $"_field{fieldName.Length}_{fieldName}"
        );
    }

    private static string EscapeCSharpIdentifier(string name) => InterpretationCSharpNames.Identifier(name);

    private static string Indent(string code, int levels)
    {
        var indent = new string(' ', levels * 4);
        var lines = code.Split('\n');
        var result = new StringBuilder();
        foreach (var line in lines)
            if (string.IsNullOrWhiteSpace(line))
                result.AppendLine();
            else
                result.AppendLine(indent + line.TrimEnd('\r'));
        return result.ToString().TrimEnd();
    }
}
